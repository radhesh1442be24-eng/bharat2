export function getMakes() {
  return Array.from(new Set(VEHICLE_DATABASE.map(v => v.make))).sort();
}

export function getModelsForMake(make) {
  return Array.from(
    new Set(VEHICLE_DATABASE.filter(v => v.make === make).map(v => v.model))
  ).sort();
}

export function getVariantsForModel(make, model) {
  return VEHICLE_DATABASE.filter(v => v.make === make && v.model === model);
}

export function getVehicleByDetails(make, model, variant) {
  return VEHICLE_DATABASE.find(
    v => v.make === make && v.model === model && v.variant === variant
  ) || null;
}
